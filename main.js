async function runConcurrent(items, limit, fn) {
  if (items.length === 0)
    return;
  const queue = [...items];
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (queue.length > 0) {
      const item = queue.shift();
      if (item !== void 0) {
        await fn(item);
      }
    }
  });
  await Promise.all(workers);
}
